--
-- Sealed sender: ключи доступа и жалобы на спам (раздел 15.2).
--
-- # Задача, которую решает эта миграция
--
-- При sealed sender отправитель не аутентифицируется: конверт приходит
-- без имени и без подписи. Само по себе это открывает сервер любому,
-- кто захочет завалить чужую очередь мусором.
--
-- Ответ — ключ доступа получателя. Получатель выводит его из своего
-- профиля и раздаёт только тем, с кем согласен переписываться; сервер
-- знает лишь его хеш и проверяет предъявленный ключ, не узнавая,
-- **кто** его предъявил. То есть анонимность отправителя сохраняется,
-- а «писать анонимно кому угодно» — нет.

-- Ключ доступа для анонимной отправки.
--
-- Дамп даёт: хеш ключа доступа устройства. По нему нельзя ни
-- восстановить сам ключ, ни узнать, кому получатель его раздал:
-- раздача происходит внутри E2EE-переписки и на сервере не видна.
CREATE TABLE sealed_sender_access (
    device_id      UUID PRIMARY KEY REFERENCES devices(device_id) ON DELETE CASCADE,

    -- SHA-256 от ключа доступа, а не сам ключ.
    --
    -- 🔐 Утечка дампа не позволяет писать пользователю анонимно:
    -- предъявить нужно прообраз, а его в базе нет.
    access_key_hash BYTEA NOT NULL,

    -- Принимать ли конверты вообще без ключа доступа.
    --
    -- По умолчанию false: анонимная отправка кому угодно — это спам
    -- по построению. Пользователь может включить приём от всех, если
    -- ему важнее доступность, чем тишина.
    allow_from_anyone BOOLEAN NOT NULL DEFAULT FALSE,

    updated_at     TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT access_key_hash_len CHECK (octet_length(access_key_hash) = 32)
);

-- Жалобы на спам, отправленный через sealed sender.
--
-- # Как это работает
--
-- Сервер при доставке не знает отправителя. Узнать его он может
-- только от получателя: тот расшифровывает конверт, достаёт оттуда
-- сертификат отправителя — подписанный самим же сервером — и
-- предъявляет его вместе с жалобой.
--
-- 🔐 Это единственный путь: доказательство приходит от того, кто
-- пострадал, и подтверждается подписью, которую сервер узнаёт как
-- свою. Сервер не может ни сфабриковать жалобу, ни раскрыть
-- отправителя без участия получателя.
--
-- Дамп даёт: кто на кого пожаловался и когда. Это метаданные,
-- и они здесь неизбежны — жалоба без указания на кого бессмысленна.
CREATE TABLE sealed_sender_reports (
    report_id        UUID PRIMARY KEY,

    -- На кого жалуются: извлекается из проверенного сертификата,
    -- а не из слов жалобщика.
    reported_account UUID NOT NULL,
    reported_device  UUID NOT NULL,

    -- Кто жалуется.
    complainant_device  UUID NOT NULL REFERENCES devices(device_id) ON DELETE CASCADE,

    -- Время округляется до часа при выдаче, как и всё остальное
    -- (раздел 15.4).
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX sealed_sender_reports_by_reported
    ON sealed_sender_reports (reported_account, created_at);

-- Один жалобщик — одна жалоба на одного отправителя.
--
-- Без этого один человек накрутил бы счётчик жалоб на неугодного,
-- и число жалоб перестало бы что-либо значить.
CREATE UNIQUE INDEX sealed_sender_reports_unique
    ON sealed_sender_reports (complainant_device, reported_device);
