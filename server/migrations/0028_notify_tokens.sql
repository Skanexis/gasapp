-- Токены уведомлений (ADR-040).
--
-- Приложение в фоне заперто: база и ключ устройства закрыты PIN, и
-- подписать запрос «есть ли у меня новое» ему нечем. Поэтому устройство
-- заводит отдельный случайный токен, хранит его вне зашифрованной базы
-- и по нему спрашивает ровно одно: непуста ли очередь.
--
-- 🔐 Сервер хранит только SHA-256 токена. Токен не даёт ни прочитать
-- очередь, ни забрать её, ни подписать что-либо — только узнать «да»
-- или «нет». Времени и счётчиков обращений здесь нет: журнала того,
-- когда телефон просыпался, сервер не ведёт.

CREATE TABLE notify_tokens (
    device_id  UUID PRIMARY KEY REFERENCES devices(device_id) ON DELETE CASCADE,
    token_hash BYTEA NOT NULL CHECK (octet_length(token_hash) = 32)
);
