-- 0007: метки, которые сервер хранил, но ни для чего не использовал.
--
-- # Что здесь чинится
--
-- Сверка «что знает сервер» (2026-09-24) нашла четыре столбца, которые
-- заполняли умолчания базы и не читал ни один запрос:
--
-- * `accounts.created_at` и `devices.created_at` — точное время
--   регистрации. В паре с внешними наблюдениями (кто в эту минуту
--   ставил приложение) оно связывает аккаунт с человеком;
-- * `devices.last_seen_at` — когда устройство было в сети. Не писался
--   никогда, но столбец обещал, что будет; первый же, кто решил бы
--   «заполнить пропуск», завёл бы журнал присутствия;
-- * `devices.device_name` — имя устройства открытым текстом («Pixel
--   Ани»). Не присылается клиентом, но схема его ждала.
--
-- Сервер без этих столбцов работает так же — их не читал никто.
-- Удаляются, а не зануляются: пустой столбец — приглашение его
-- заполнить.

ALTER TABLE accounts DROP COLUMN IF EXISTS created_at;

ALTER TABLE devices
    DROP COLUMN IF EXISTS created_at,
    DROP COLUMN IF EXISTS last_seen_at,
    DROP COLUMN IF EXISTS device_name;
