--
-- Токены push-уведомлений.
--
-- 🔐 Токен — это идентификатор, по которому Apple или Google доставляют
-- уведомление на конкретное устройство. Он не даёт читать переписку,
-- но связывает устройство AEGIS с аккаунтом у посредника, поэтому
-- хранится как можно скупее: только сам токен, провайдер и устройство.
--
-- Время создания не хранится: оно позволяло бы строить историю смены
-- устройств, а для работы push не нужно.

CREATE TABLE IF NOT EXISTS push_tokens (
    -- Устройство: у каждого ровно один действующий токен.
    --
    -- PRIMARY KEY, а не отдельный идентификатор: второй токен для
    -- одного устройства означал бы доставку на старый аппарат,
    -- с которого пользователь уже ушёл.
    device_id UUID PRIMARY KEY
        REFERENCES devices (device_id) ON DELETE CASCADE,

    -- Провайдер: 'fcm' или 'apns'.
    --
    -- Текст, а не перечисление: список провайдеров меняется чаще,
    -- чем схема, и UnifiedPush уже на подходе.
    provider TEXT NOT NULL,

    -- Сам токен, как его выдал провайдер.
    token TEXT NOT NULL,

    CONSTRAINT push_provider_known CHECK (provider IN ('fcm', 'apns', 'unified'))
);

-- Удаление устройства снимает токен каскадом: без этого уведомления
-- продолжали бы уходить на аппарат, который больше не принадлежит
-- аккаунту.
