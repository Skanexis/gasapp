-- 0011: аккаунт, не появлявшийся год, удаляется вместе с именем.
--
-- # Зачем
--
-- Имя закреплено за аккаунтом, пока аккаунт существует: переустановка
-- приложения его не освобождает (вернуть аккаунт — восстановлением
-- из резервной копии). Без срока брошенные аккаунты держали бы имена
-- вечно. Решение владельца: год без входа — аккаунт удаляется, имя
-- освобождается.
--
-- # 🔐 Почему месяц, а не время
--
-- Правилу «год без входа» достаточно месяца последней активности.
-- Точное время было бы журналом присутствия — тем самым, что миграция
-- 0007 удалила (`last_seen_at`). Месяц на весь аккаунт не говорит,
-- когда человек бывает в сети, и не различает его устройства.
--
-- Существующим аккаунтам ставится текущий месяц: срок отсчитывается
-- с этой миграции, а не задним числом.

ALTER TABLE accounts
    ADD COLUMN active_month DATE NOT NULL DEFAULT date_trunc('month', now())::date;
