-- Суточный бюджет токенов бота (аудит 2026-10-10, N-1).
--
-- Бот регистрируется без почты: его «почта» — токен владельца. Предел
-- был только на число ботов разом (20), а удаление бота освобождало
-- место. Премиум-аккаунт поэтому мог заводить бота, рассылать с него,
-- удалять и заводить нового — сколько угодно свежих аккаунтов в обход
-- правила «один адрес — один аккаунт».
--
-- Теперь токены считаются за сутки. Хранится день и число, а не время
-- каждого токена: журнала действий владельца сервер не ведёт.

ALTER TABLE accounts
    ADD COLUMN bot_tokens_day   DATE,
    ADD COLUMN bot_tokens_taken SMALLINT NOT NULL DEFAULT 0
        CHECK (bot_tokens_taken >= 0);
