-- Удостоверение участника закрытого канала (аудит 2026-10-10, N-0).
--
-- Ключ новой эпохи тот, кто ведёт канал, шифрует под ключи доставки
-- участников, а список этих ключей получает от сервера. Устройство
-- верило первому ключу, увиденному под аккаунтом, — и сервер, назвав
-- выдуманного «участника» со своим ключом, получал ключ канала.
--
-- Теперь рядом с ключом доставки лежит удостоверение: подпись того, кто
-- ведёт канал (владельца либо действующего администратора), под этим
-- ключом доставки и номером эпохи. Сервер его хранит и отдаёт, но
-- подделать не может: ключа подписи канала у него нет. Ключ эпохи
-- получает только участник с удостоверением.
--
-- Для сервера это непрозрачные 100 байт: эпоха(4) ‖ кто подписал(32) ‖
-- подпись(64).

ALTER TABLE channel_member_keys
    ADD COLUMN approval BYTEA CHECK (approval IS NULL OR octet_length(approval) = 100);
