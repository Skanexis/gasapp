--
-- Хранилище зашифрованных вложений.
--
-- 🔐 Что сервер здесь хранит и чего не знает
--
-- Хранит: непрозрачный блоб и его длину. Не знает: имя файла, его тип,
-- длительность голосового, размер картинки, ключ расшифровки. Всё это
-- уходит получателю **внутри сообщения**, то есть под сквозным
-- шифрованием, — см. `aegis-media::descriptor`.
--
-- Имя файла шифруется не из педантизма: «результаты анализов.jpg» или
-- «договор аренды.pdf» говорят о человеке больше, чем сам факт отправки
-- файла. Хранилище, знающее имена, знает переписку почти целиком.
--
-- # Почему нет ссылки на получателя
--
-- Строка вложения не называет, кому файл предназначен. Связь между
-- файлом и разговором существует только в сообщении, которое сервер
-- прочитать не может. Добавь сюда destination_device_id — и оператор
-- строил бы граф «кто кому шлёт файлы», не расшифровав ни байта.
--
-- Плата за это — невозможность удалить вложения вместе с аккаунтом.
-- Их убирает срок хранения, общий для всех.

CREATE TABLE IF NOT EXISTS attachments (
    -- Адрес блоба. Он же попадает в описание вложения внутри
    -- сообщения.
    --
    -- UUID, а не хеш содержимого: одинаковые файлы у разных людей
    -- получили бы один адрес, и сервер узнавал бы, что двое переслали
    -- друг другу одно и то же.
    attachment_id UUID PRIMARY KEY,

    -- Кто загрузил.
    --
    -- 🔐 Нужен только для учёта квоты: без него один аккаунт занял бы
    -- диск целиком. Получателя здесь нет намеренно — см. выше.
    uploader_device_id UUID NOT NULL REFERENCES devices(device_id) ON DELETE CASCADE,

    -- Сам шифроблоб: чанки по 64 КБ + 16 байт тега каждый.
    payload BYTEA NOT NULL,

    uploaded_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    -- Срок хранения. Общий для всех: вложение живёт столько же,
    -- сколько недоставленный конверт.
    expires_at TIMESTAMPTZ NOT NULL
);

CREATE INDEX attachments_by_expiry ON attachments (expires_at);

-- Учёт квоты идёт по загрузившему устройству.
CREATE INDEX attachments_by_uploader ON attachments (uploader_device_id);

-- Предел размера блоба — 100 МБ плюс накладные расходы шифрования.
--
-- 100 МБ — предел одного вложения (`aegis-media::descriptor`).
-- Накладные: 16 байт тега на каждый чанк в 64 КБ, то есть примерно
-- 1/4096 от объёма. Округлено вверх до 101 МБ с запасом.
--
-- Проверка на уровне схемы, а не только в коде: она действует и для
-- запросов, написанных в обход API.
ALTER TABLE attachments
    ADD CONSTRAINT attachments_payload_size
    CHECK (octet_length(payload) <= 101 * 1024 * 1024);
