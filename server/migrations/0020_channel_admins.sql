-- 0020: администраторы каналов.
--
-- Владелец канала называет аккаунты, которым сервер разрешает писать
-- в канал: публиковать, править и удалять записи, загружать файлы.
-- Название, закреп, аватар, публичное имя, состав администраторов
-- и удаление канала остаются за владельцем.
--
-- # 🔐 Что это значит для сервера и чего не значит
--
-- * Эта таблица — только право **сервера** принять запрос. Подлинность
--   записи она не определяет: читатели принимают запись, если она
--   подписана ключом владельца либо ключом администратора из описания
--   канала, а описание подписывает владелец. Сервер, вписавший сюда
--   строку сам, получит записи, которые читатели отвергнут.
-- * Дамп даёт: какие аккаунты ведут какие каналы. Владелец канала был
--   известен серверу и раньше; теперь известны и администраторы.
-- * `verify_key` — публичный ключ, которым администратор подписывает
--   записи. Он же лежит в зашифрованном описании канала. Серверу он
--   нужен как имя строки: по нему владелец снимает администратора.

CREATE TABLE channel_admins (
    channel_id UUID NOT NULL REFERENCES channels(channel_id) ON DELETE CASCADE,
    account_id UUID NOT NULL REFERENCES accounts(account_id) ON DELETE CASCADE,
    verify_key BYTEA NOT NULL CHECK (octet_length(verify_key) = 32),
    -- С точностью до часа, как у остальных таблиц каналов.
    added_at   TIMESTAMPTZ NOT NULL DEFAULT date_trunc('hour', now()),
    PRIMARY KEY (channel_id, account_id),
    UNIQUE (channel_id, verify_key)
);

-- «Пишет ли этот аккаунт в этот канал» — при каждой публикации.
CREATE INDEX channel_admins_by_account ON channel_admins (account_id);
