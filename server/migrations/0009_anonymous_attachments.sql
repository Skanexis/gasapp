-- 0009: вложения без загрузчика.
--
-- # Зачем
--
-- Загрузка была подписана устройством, и сервер помнил, кто и в какой
-- час прислал каждый файл. Теперь загрузка анонимна: право на место
-- доказывается proof-of-work над самим блобом, и загрузчика у новых
-- строк нет.
--
-- # Чем за это заплачено
--
-- Квота на устройство держалась на этом столбце. Её заменяют работа,
-- растущая с размером, и общий потолок хранилища вложений (см.
-- `repo::store_attachment`). Удаление аккаунта больше не уносит его
-- вложения: связи с аккаунтом у них нет. Они шифроблобы без ключа
-- и истекают сами — не позже `expires_at`.

ALTER TABLE attachments ALTER COLUMN uploader_device_id DROP NOT NULL;
