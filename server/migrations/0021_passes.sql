-- 0021: пропуска — анонимные одноразовые права, выданные вслепую.
--
-- Подписка на канал анонимна, и её нечем было ограничить, кроме
-- proof-of-work: счётчик подписчиков накручивался циклом. Теперь
-- подписка стоит пропуска. Пропуск выдаётся аккаунту (за подписью
-- устройства, не больше сорока в сутки) и тратится анонимно; сервер
-- подписывает замаскированную точку и связать выданное с потраченным
-- не может (`gasapp-server-api::pass`).
--
-- # 🔐 Что даёт дамп
--
-- * `pass_quota`: какой аккаунт сколько пропусков взял за последние
--   двое суток. Не каналы: на что пропуск пойдёт, при выдаче неизвестно.
-- * `spent_passes`: хеши потраченных зёрен и день. Не аккаунты и не
--   каналы.
--
-- Строку одной таблицы со строкой другой не связать: в этом смысл
-- слепой выдачи.

CREATE TABLE pass_quota (
    account_id UUID NOT NULL REFERENCES accounts(account_id) ON DELETE CASCADE,
    day        DATE NOT NULL,
    issued     INTEGER NOT NULL CHECK (issued > 0),
    PRIMARY KEY (account_id, day)
);

-- Потраченные пропуска. Не удаляются: ключ пропусков узла не меняется,
-- и забытый потраченный пропуск стал бы снова годным. Строка — 32 байта
-- хеша и дата.
CREATE TABLE spent_passes (
    seed_hash BYTEA PRIMARY KEY CHECK (octet_length(seed_hash) = 32),
    spent_on  DATE NOT NULL DEFAULT current_date
);
