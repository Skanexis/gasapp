-- Жалобы: каким сертификатом доказана каждая (аудит 2026-10-02, S-4).
--
-- 🔐 Сертификат отправителя — предъявительский: кто его держит, тот и
-- жалуется. Получив одно сообщение, жалобщик заводил десяток аккаунтов
-- (регистрация — секунды работы) и жаловался с каждого тем же
-- сертификатом: в админ-центре это выглядело как «10 разных людей».
-- Теперь видно и число разных сертификатов. Настоящий спам приходит
-- многим и в разные сутки — разными сертификатами; накрутка одним
-- полученным сообщением — одним.
--
-- Хранится SHA-256 сертификата, не сам сертификат: сравнивать хеши
-- достаточно, а сам сертификат — ещё одна копия ключа отправителя.

ALTER TABLE sealed_sender_reports
    ADD COLUMN certificate_hash BYTEA
        CHECK (certificate_hash IS NULL OR octet_length(certificate_hash) = 32);
