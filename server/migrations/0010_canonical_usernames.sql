-- 0010: имя пользователя — только в каноничной форме.
--
-- # Зачем
--
-- `UNIQUE` сравнивал имена побайтно. «alice», «Alice», «аlice»
-- с кириллической «а» и «alice» с невидимым символом были разными
-- аккаунтами — и выглядели одинаково. Найдя «alice», человек мог
-- написать самозванцу. Теперь имя — строчные латинские буквы, цифры
-- и подчёркивание, с буквы, от 3 до 32 символов: два разных имени
-- различимы глазом.
--
-- # Почему NOT VALID
--
-- Ограничение действует на каждую новую и изменённую строку. Старые
-- строки не проверяются: база разработки хранит имена прежних тестов,
-- а боевой базы до этой миграции не было.

ALTER TABLE accounts
    ADD CONSTRAINT username_is_canonical
        CHECK (username ~ '^[a-z][a-z0-9_]{2,31}$') NOT VALID;
