#!/usr/bin/env bash
# SPDX-License-Identifier: AGPL-3.0-only
#
# Резервное копирование базы AEGIS.
#
# # 🔐 Что копируется и что НЕ копируется
#
# Копируются: аккаунты, устройства, предключи, токены push.
# Их потеря означает, что все пользователи должны регистрироваться
# заново, теряя переписку — восстановить их неоткуда.
#
# **Конверты (`envelopes`) намеренно исключены.** Они удаляются сразу
# после доставки, и это не оптимизация, а обещание: сообщение не
# хранится на сервере. Бэкап вернул бы к жизни то, что пользователь
# считает удалённым, — и сделал бы изъятие резервной копии
# равносильным изъятию переписки.
#
# Цена решения: при восстановлении из бэкапа недоставленные сообщения
# теряются. Отправители увидят их как отправленные, получатели
# не получат. Это лучше, чем хранить их дольше, чем обещано.
#
# **Вложения (`attachments`) исключены по той же причине.** Они живут
# тридцать суток, а бэкап — ещё до четырнадцати после снятия: вложение,
# попавшее в последний перед истечением бэкап, пережило бы свой срок
# почти на две недели. Вместе с ним пережила бы его и строка «кто
# загрузил» — единственная запись на сервере, связывающая вложение
# с отправителем.
#
# ⚠️ До 2026-09 вложения в бэкап попадали, а документ о сроках хранения
# обещал им тридцать суток. Цена исключения та же: после восстановления
# вложения, которые получатель не успел скачать, не скачиваются.
#
# # Про шифрование
#
# Бэкап содержит публичные ключи и предключи — не секреты, но связка
# «кто зарегистрирован» целиком. Файл шифруется age или gpg **до**
# того, как покинет машину: незашифрованный дамп на промежуточном
# диске переживёт удаление и попадёт в чужие руки вместе с ним.
#
# # Запуск
#
#     ./backup.sh /var/backups/aegis
#
# Из cron, ежедневно:
#
#     0 4 * * * /opt/aegis/backup.sh /var/backups/aegis

set -euo pipefail

readonly TARGET="${1:?укажите каталог для бэкапов}"
readonly DB_NAME="${AEGIS_DB_NAME:-aegis}"
readonly DB_USER="${AEGIS_DB_USER:-aegis}"

# Ключ шифрования: публичная часть age-ключа получателя.
#
# Публичная, а не приватная: машина, делающая бэкап, не должна уметь
# его прочитать. Иначе взлом сервера даёт и текущие данные,
# и всю историю.
#
# Берётся из переменной, а если её нет — из файла, который пишет
# rotate-backup-key.sh. ⚠️ Прежде читалась только переменная: ротация
# писала нового получателя в файл, которого этот скрипт не видел, и
# копии продолжали шифроваться прежним ключом — тем, который ротация
# предлагала со временем удалить. А строка cron ниже переменную
# не задаёт вовсе.
readonly RECIPIENT_FILE="${AEGIS_BACKUP_RECIPIENT_FILE:-/etc/aegis/backup-recipient}"

AGE_RECIPIENT="${AEGIS_BACKUP_AGE_RECIPIENT:-}"
if [[ -z "$AGE_RECIPIENT" && -r "$RECIPIENT_FILE" ]]; then
    AGE_RECIPIENT="$(tr -d '[:space:]' < "$RECIPIENT_FILE")"
fi
readonly AGE_RECIPIENT

# Сколько бэкапов хранить.
#
# Четырнадцать: две недели покрывают типичный срок обнаружения
# проблемы. Хранить дольше — значит хранить связку «кто
# зарегистрирован» дольше, чем нужно для восстановления.
readonly KEEP="${AEGIS_BACKUP_KEEP:-14}"

readonly STAMP="$(date -u +%Y%m%d-%H%M%S)"
readonly DUMP="${TARGET}/aegis-${STAMP}.sql"

mkdir -p "$TARGET"

# 🔐 Права до создания файла, а не после: между созданием и chmod
# файл читается всеми, и этого окна достаточно.
umask 077

# 🔐 Открытый дамп не переживает сбой.
#
# Ловушка на любой выход: если шифрование не удалось — нет age, кончилось
# место, неверный получатель, — set -e обрывает скрипт, и без неё
# незашифрованный дамп со связкой «кто зарегистрирован» оставался бы
# в каталоге копий. Проверено: так и было.
KEEP_PLAINTEXT=0
cleanup() {
    if [[ "$KEEP_PLAINTEXT" != "1" && -f "$DUMP" ]]; then
        shred --remove --zero "$DUMP" 2>/dev/null || rm -f "$DUMP"
    fi
}
trap cleanup EXIT

echo "снимок базы ${DB_NAME} без конвертов и вложений"

# --exclude-table-data, а не --exclude-table: структура таблицы нужна,
# чтобы восстановленная база была работоспособной. Исключаются только
# данные.
pg_dump \
    --username="$DB_USER" \
    --dbname="$DB_NAME" \
    --exclude-table-data='envelopes' \
    --exclude-table-data='attachments' \
    --no-owner \
    --no-privileges \
    --file="$DUMP"

# 🔐 Проверка, что конверты действительно не попали в дамп.
#
# До шифрования, а не после: зашифрованный файл прочитать нечем,
# и проверка после него не выполнялась бы вовсе — то есть создавала
# бы ложное чувство, что контроль есть.
#
# Не «на всякий случай»: ошибка в имени таблицы или смена флага
# pg_dump тихо включила бы конверты обратно, и обещание «сообщения
# не хранятся» перестало бы выполняться без единого сообщения
# об ошибке.
for table in envelopes attachments; do
    if grep -qE "^COPY public\.${table} .* FROM stdin;" "$DUMP"; then
        echo "ОШИБКА: в дамп попали данные таблицы ${table}" >&2
        shred --remove --zero "$DUMP" 2>/dev/null || rm -f "$DUMP"

        exit 1
    fi
done

if [[ -n "$AGE_RECIPIENT" ]]; then
    echo "шифрование бэкапа"
    age --recipient "$AGE_RECIPIENT" --output "${DUMP}.age" "$DUMP"

    # 🔐 Затирание, а не просто удаление: на журналируемой файловой
    # системе rm оставляет содержимое читаемым до перезаписи блоков.
    shred --remove --zero "$DUMP" 2>/dev/null || rm -f "$DUMP"

    readonly RESULT="${DUMP}.age"
elif [[ "${AEGIS_BACKUP_ALLOW_PLAINTEXT:-}" == "1" ]]; then
    # Только явно — для проверки на стенде. Случайно так не выйдет.
    echo "⚠️  бэкап НЕ зашифрован (AEGIS_BACKUP_ALLOW_PLAINTEXT=1)" >&2

    KEEP_PLAINTEXT=1
    readonly RESULT="$DUMP"
else
    # 🔐 Без получателя копия не остаётся на диске.
    #
    # Прежде здесь было предупреждение в stderr — которое при запуске
    # из cron никто не читает, — а незашифрованный дамп со связкой
    # «кто зарегистрирован» оставался лежать.
    echo "ОШИБКА: получатель шифрования не задан" >&2
    echo "  ни AEGIS_BACKUP_AGE_RECIPIENT, ни файла $RECIPIENT_FILE" >&2
    shred --remove --zero "$DUMP" 2>/dev/null || rm -f "$DUMP"

    exit 1
fi

echo "готово: ${RESULT}"

# Ротация: удаляются самые старые сверх лимита.
#
# По времени изменения, а не по имени: имя зависит от часового пояса
# машины, и при его смене сортировка разъехалась бы.
find "$TARGET" -maxdepth 1 -name 'aegis-*.sql*' -printf '%T@ %p\n' \
    | sort -rn \
    | tail -n "+$((KEEP + 1))" \
    | cut -d' ' -f2- \
    | while read -r old; do
        echo "удаление старого бэкапа: $(basename "$old")"
        shred --remove --zero "$old" 2>/dev/null || rm -f "$old"
    done
