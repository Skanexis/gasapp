#!/usr/bin/env bash
# SPDX-License-Identifier: AGPL-3.0-only
#
# Ротация ключа шифрования резервных копий.
#
# # Зачем ротация
#
# Ключ, живущий вечно, накапливает риск: чем дольше он существует,
# тем больше мест, где он мог оказаться — старые ноутбуки, чужие
# резервные копии, переписка с коллегой. Смена ключа раз в полгода
# ограничивает ущерб от утечки прошлым периодом.
#
# # 🔐 Почему старый ключ нельзя удалять сразу
#
# Копии, сделанные прежним ключом, расшифровываются только им.
# Удалив его в день ротации, вы теряете возможность восстановиться
# из всего, что было снято раньше, — то есть ротация превращается
# в потерю бэкапов.
#
# Поэтому скрипт **не удаляет** старый ключ, а помечает его датой
# вывода из обращения и сообщает, когда его можно будет удалить:
# когда истечёт последняя копия, зашифрованная им.
#
# # Что делает скрипт
#
# 1. Создаёт новый ключ.
# 2. Переводит бэкапы на его публичную часть.
# 3. Архивирует старый ключ с датой.
# 4. Печатает дату, после которой старый ключ можно удалить.
#
# Перешифровывать старые копии он **не** пытается: для этого пришлось
# бы расшифровать их все на диске, а незашифрованный дамп на диске —
# ровно то, чего избегает вся эта схема.
#
# # Запуск
#
#     ./rotate-backup-key.sh
#
# Из cron, раз в полгода:
#
#     0 3 1 1,7 * /opt/aegis/rotate-backup-key.sh

set -euo pipefail

# Каталог ключей. Приватные части лежат ТОЛЬКО здесь и только
# на машине администратора — не на сервере бэкапов.
readonly KEY_DIR="${AEGIS_BACKUP_KEY_DIR:-/root/aegis-keys}"

# Файл с публичной частью, который читает backup.sh.
readonly RECIPIENT_FILE="${AEGIS_BACKUP_RECIPIENT_FILE:-/etc/aegis/backup-recipient}"

# Сколько дней хранятся копии — из настроек backup.sh.
readonly KEEP_DAYS="${AEGIS_BACKUP_KEEP:-14}"

readonly STAMP="$(date -u +%Y%m%d)"
readonly NEW_KEY="${KEY_DIR}/aegis-backup-${STAMP}.key"
# Указатель на текущий ключ.
#
# Обычный файл с именем, а не символьная ссылка: ссылки ведут себя
# по-разному между системами (в Git Bash `ln -s` молча копирует),
# и скрипт, полагающийся на них, ломается там, где его не проверяли.
readonly CURRENT="${KEY_DIR}/current"

# 🔐 Права до создания файлов: приватный ключ, созданный с обычными
# правами, читается всеми в промежутке до chmod.
umask 077

mkdir -p "$KEY_DIR"

if [[ -f "$NEW_KEY" ]]; then
    echo "ключ за сегодня уже создан: $NEW_KEY" >&2
    echo "повторная ротация в тот же день перезаписала бы его" >&2
    exit 1
fi

echo "создание нового ключа"
age-keygen -o "$NEW_KEY" 2>/dev/null

new_recipient="$(age-keygen -y "$NEW_KEY")"

# Архивирование прежнего ключа.
#
# Переименование, а не удаление: им расшифровываются копии, снятые
# до сегодняшнего дня.
if [[ -f "$CURRENT" ]]; then
    previous="${KEY_DIR}/$(cat "$CURRENT")"
    retired="${previous%.key}-выведен-${STAMP}.key"

    if [[ -f "$previous" && "$previous" != "$NEW_KEY" ]]; then
        mv "$previous" "$retired"
        echo "прежний ключ выведен из обращения: $(basename "$retired")"

        # Дата, после которой прежний ключ больше ничего не расшифровывает.
        expiry="$(date -u -d "+${KEEP_DAYS} days" +%Y-%m-%d 2>/dev/null \
            || date -u -v "+${KEEP_DAYS}d" +%Y-%m-%d)"

        echo "$expiry" > "${retired}.удалить-после"

        echo
        echo "⚠️  НЕ УДАЛЯЙТЕ прежний ключ до ${expiry}."
        echo "⚠️  До этой даты им расшифровываются существующие копии."
        echo
    fi
fi

basename "$NEW_KEY" > "$CURRENT"

# Публичная часть уходит на сервер бэкапов; приватная остаётся здесь.
mkdir -p "$(dirname "$RECIPIENT_FILE")"
echo "$new_recipient" > "$RECIPIENT_FILE"

echo "новый получатель записан в $RECIPIENT_FILE"
echo
echo "Дальше:"
echo "  1. Скопируйте $RECIPIENT_FILE на сервер бэкапов (VPS-4)"
echo "  2. Убедитесь, что там AEGIS_BACKUP_AGE_RECIPIENT читает этот файл"
echo "  3. 🔐 Приватный ключ ($NEW_KEY) на сервер НЕ копируйте"
echo
echo "Ключи, которые можно удалить сегодня:"

today="$(date -u +%Y-%m-%d)"
found=0

for marker in "${KEY_DIR}"/*.удалить-после; do
    [[ -f "$marker" ]] || continue

    expiry="$(cat "$marker")"

    if [[ "$today" > "$expiry" ]]; then
        echo "  ${marker%.удалить-после} (истёк $expiry)"
        found=1
    fi
done

if [[ $found -eq 0 ]]; then
    echo "  нет — все прежние ключи ещё нужны"
fi
