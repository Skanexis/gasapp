#![no_main]

//! Фаззинг разбора содержимого сообщения.
//!
//! Содержимое разбирается после расшифровки, то есть приходит
//! от владельца ключа сессии. Добросовестным это его не делает:
//! собеседник волен собрать сообщение своей реализацией, и каждая
//! длина, счётчик и флаг в нём — его выбор. Модуль `content` обещал
//! покрытие фаззингом, а таргета не было.
//!
//! Что ищется: паника на любом входе и расхождение туда-обратно —
//! разобранное содержимое, записанное заново, обязано читаться
//! в то же самое. Расхождение значило бы, что писатель и читатель
//! проверяют разные пределы.

use gasapp_protocol::content::Content;
use libfuzzer_sys::fuzz_target;

fuzz_target!(|data: &[u8]| {
    // Без padding: так фаззер доходит до разбора полей, а не тратит
    // каждый вход на снятие дополнения.
    if let Ok(content) = Content::from_unpadded_bytes(data) {
        let again = content
            .to_unpadded_bytes()
            .expect("разобранное содержимое обязано записываться");

        assert_eq!(
            Content::from_unpadded_bytes(&again).expect("записанное обязано читаться"),
            content,
        );
    }

    // И с padding — путь, которым идёт настоящий вход.
    let _ = Content::from_bytes(data);
});
