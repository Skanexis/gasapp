#![no_main]

//! Фаззинг разбора сохранённого состояния сессии.
//!
//! Состояние читается из собственной зашифрованной базы, то есть источник
//! доверенный — но повреждение файла (сбой диска, обрыв записи, откат
//! файловой системы) не должно ронять приложение. Пользователь с
//! повреждённой базой обязан получить ошибку и возможность переустановить
//! сессию, а не бесконечный краш при запуске.
//!
//! Что ищется: паника при разборе — выход за границу буфера,
//! переполнение счётчика пропущенных ключей, некорректная длина ключа.

use gasapp_protocol::{double_ratchet::RatchetState, keys::SessionState};
use gasapp_types::Secret;
use libfuzzer_sys::fuzz_target;

fuzz_target!(|data: &[u8]| {
    let session = SessionState::from_serialized(Secret::new(data.to_vec()));

    // Любые байты обязаны дать либо корректное состояние, либо ошибку.
    if let Ok(state) = RatchetState::deserialize(&session) {
        // Разобранное состояние должно быть пригодно к использованию:
        // обращение к нему не должно паниковать.
        let _ = state.skipped_count();

        // Повторная сериализация не должна паниковать на данных,
        // которые сами пришли из разбора.
        let _ = state.serialize();
    }
});
