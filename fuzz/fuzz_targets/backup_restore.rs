#![no_main]

//! Фаззинг разбора файла резервной копии.
//!
//! # Почему этот вход недоверенный
//!
//! Файл копии лежит там, куда его положил пользователь: в облаке,
//! на флешке, в мессенджере. Тег AEAD доказывает, что тело собрано
//! владельцем recovery key, — но **заголовок читается до проверки
//! тега**, потому что без соли и параметров из него ключ не вывести.
//! То есть заголовок разбирается на данных, которые пишет кто угодно,
//! кто держит файл в руках.
//!
//! Отсюда два разных сценария в одном таргете:
//!
//! 1. разбор заголовка вообще без ключа — здесь атакующий свободен;
//! 2. полный разбор с известным ключом — путь, по которому идут
//!    байты после успешной расшифровки. Тег их подтвердил, но тело
//!    могла собрать сломанная версия приложения, и разбор обязан
//!    отвечать ошибкой, а не паникой.
//!
//! Что ищется: паника, переполнение при вычислении длин, попытка
//! выделить память по числу из файла и зацикливание на разборе.

use gasapp_backup::archive::ArchiveHeader;
use gasapp_backup::bundle::BackupBundle;
use gasapp_backup::{BackupChain, RecoveryKey};
use libfuzzer_sys::fuzz_target;

fuzz_target!(|data: &[u8]| {
    // 1. Заголовок: то, что разбирается без всякого ключа.
    //
    // Здесь же проверяются границы параметров Argon2id: заголовок
    // с непомерной памятью обязан отвергаться при разборе, а не
    // доходить до попытки выделить гигабайты.
    let _ = ArchiveHeader::from_bytes(data);

    // 2. Тело бандла: путь после успешной расшифровки.
    //
    // Вызывается напрямую, а не через расшифровку: подобрать
    // корректный тег AEAD фаззер не может, и без этого вызова
    // разбор бандла остался бы непокрытым.
    let _ = BackupBundle::from_bytes(data);

    // 3. Восстановление цепочки целиком.
    //
    // Ключ фиксирован: фаззится разбор файла, а не вывод ключей —
    // Argon2id стоит сотни миллисекунд и свёл бы число итераций
    // к бесполезному.
    let key = RecoveryKey::from_bytes([0x42u8; 32]);
    let _ = BackupChain::restore(&key, &[data.to_vec()]);
});
