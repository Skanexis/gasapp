#![no_main]

//! Фаззинг разбора ссылки на контакт `aegis://contact/...`.
//!
//! # Почему именно этот разбор
//!
//! Это единственная внешняя точка входа приложения на Android:
//! `AddContactActivity` экспортирована и объявляет `intent-filter`
//! на схему `aegis`. Значит, ссылку сюда подаёт **любое** приложение
//! на устройстве и любая страница, открытая в браузере, — без участия
//! пользователя и без каких-либо ограничений на содержимое.
//!
//! Раздел 19.2 называет это прямо: «Deep link `aegis://` — валидировать
//! вход, это внешняя точка входа (fuzzing!)». Таргета при этом не было.
//!
//! # Что ищется
//!
//! Паника на любом входе: обрезанный префикс, повторная схема внутри
//! ссылки, лишние сегменты пути, параметры без значения, проценты
//! без двух цифр после них, многобайтовый UTF-8 на границе предельной
//! длины имени — везде, где разбор режет строку по индексу.
//!
//! 🔐 Паника здесь — не «ошибка разбора», а отказ приложения по чужой
//! команде: достаточно прислать ссылку в любом мессенджере.
//!
//! # Что проверяется сверх отсутствия паники
//!
//! Круговой обход: разобранная ссылка собирается обратно и разбирается
//! ещё раз. Расхождение означало бы, что показанное пользователю
//! и сохранённое в контактах — разные вещи, а это ровно та подмена,
//! от которой ссылка и защищает.

use aegis_protocol::contact_link::ContactLink;
use libfuzzer_sys::fuzz_target;

fuzz_target!(|data: &[u8]| {
    // Вход трактуется как строка: на платформе ссылка приходит из
    // `Intent.getData()`, то есть уже как текст. Некорректный UTF-8
    // до разбора не доходит.
    let Ok(text) = core::str::from_utf8(data) else {
        return;
    };

    let Ok(link) = ContactLink::parse(text) else {
        return;
    };

    // Сборка обратно не должна падать на том, что только что разобрано.
    let Ok(rebuilt) = link.to_uri() else {
        return;
    };

    // 🔐 И обязана дать ту же ссылку по смыслу. Иначе экран
    // подтверждения показывал бы одно, а в контакты попадало другое.
    let reparsed = ContactLink::parse(&rebuilt)
        .expect("пересобранная ссылка обязана разбираться");

    assert_eq!(link, reparsed, "круговой обход изменил контакт");
});
