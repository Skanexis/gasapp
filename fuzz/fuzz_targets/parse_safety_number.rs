#![no_main]

//! Фаззинг разбора safety number.
//!
//! Safety number вводит **человек** — при сверке голосом, с экрана или
//! сканированием QR. Значит, на вход попадают опечатки, обрезанные строки,
//! посторонние символы и текст на любом языке. Разбор обязан их отвергать,
//! а не паниковать: краш на экране верификации означает, что пользователь
//! не может проверить канал.
//!
//! Что ищется: паника на нечисловом вводе, на строках неверной длины
//! и на многобайтовых символах UTF-8, где длина в байтах не совпадает
//! с длиной в символах.

use gasapp_protocol::SafetyNumber;
use libfuzzer_sys::fuzz_target;

fuzz_target!(|data: &[u8]| {
    // Вход трактуется как строка: именно её вводит пользователь.
    // Некорректный UTF-8 отбрасывается — до разбора он не доходит,
    // строку формирует слой UI.
    let Ok(text) = core::str::from_utf8(data) else {
        return;
    };

    // Разбор обязан вернуть ошибку на всём, кроме 60 десятичных цифр.
    if let Ok(number) = SafetyNumber::parse(text) {
        // Успешно разобранное число обязано корректно отображаться
        // и переживать обратный разбор.
        let rendered = number.to_display_block();
        let _ = SafetyNumber::parse(&rendered);
    }
});
