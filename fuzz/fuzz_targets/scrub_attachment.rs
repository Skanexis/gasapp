#![no_main]

//! Фаззинг очистки метаданных вложений (`gasapp_media::scrub`).
//!
//! # Почему этот вход недоверенный
//!
//! Файл для отправки приходит откуда угодно: из загрузок, из чужого
//! мессенджера, с сайта. Разбор контейнера идёт до шифрования, в
//! процессе, где открыта вся переписка, — паника или зацикливание
//! здесь роняют приложение на отправке «картинки».
//!
//! Что ищется: паника, переполнение при вычислении смещений,
//! бесконечная вложенность блоков MP4, зацикливание на скане JPEG.
//! Плюс свойство: очищенный файл того же формата очищается повторно
//! без ошибок и без изменений.

use gasapp_media::scrub::{scrub, Format};
use libfuzzer_sys::fuzz_target;

fuzz_target!(|data: &[u8]| {
    if let Ok(cleaned) = scrub(data) {
        if cleaned.format != Format::Unknown {
            let again = scrub(&cleaned.bytes).expect("очищенный файл разбирается снова");
            assert_eq!(again.bytes, cleaned.bytes, "очистка не идемпотентна");
        }
    }
});
