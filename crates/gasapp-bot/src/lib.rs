//! Движок бота GasApp.
//!
//! Бот — обычный аккаунт, который ведёт программа владельца. Сервер за
//! бота ничего не делает и ключей его не видит: всё шифрование — на
//! стороне бота, как у приложения. Поэтому «API бота» здесь не веб-адрес
//! на сервере, а локальная программа:
//!
//! ```text
//! код бота (любой язык) ⇄ строки JSON ⇄ gasapp-bot ⇄ TLS ⇄ сервер GasApp
//! ```
//!
//! * [`http`] — транспорт до сервера;
//! * [`api`] — локальный HTTP-интерфейс движка и веб-хуки;
//! * [`runtime`] — команды программы бота и события для неё.
//!
//! Что бот умеет, решает его код: отвечать на сообщения, писать в
//! канал, а назначенный администратором закрытого канала — одобрять
//! заявки и удалять подписчиков. Полный список команд — в
//! `docs/bots.md`.
//!
//! # 🔐 Чего это НЕ даёт — честно
//!
//! * **Tor нет.** Сервер видит адрес машины бота.
//! * **Ключи бота лежат рядом с ним.** База зашифрована, но ключ базы —
//!   в файле в том же каталоге: защищают их права на файлы и сама
//!   машина. Кто получил каталог бота, тот получил бота.
//! * **Бот-администратор знает ключ чтения канала.** Его программа и
//!   машина становятся частью того, чему доверяет канал.

pub mod api;
pub mod http;
pub mod runtime;

pub use http::HttpTransport;
pub use runtime::Runtime;
