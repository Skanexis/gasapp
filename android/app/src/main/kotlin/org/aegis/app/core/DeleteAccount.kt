package org.aegis.app.core

import android.content.Context
import uniffi.aegis.FfiAccountDeletion

/**
 * 🔐 Удаление аккаунта целиком: сервер и устройство (MASVS PRIVACY-3.2).
 *
 * # Почему порядок живёт здесь
 *
 * Удаление состоит из двух шагов, и переставить их местами —
 * не стилистическая ошибка, а потеря переписки:
 *
 * 1. **сервер** — [uniffi.aegis.Messenger.deleteAccount];
 * 2. **устройство** — [AccountWipe.wipe].
 *
 * ⚠️ Наоборот нельзя. Запрос на удаление подписывается ключом
 * устройства; стерев ключ первым, при обрыве связи человек остаётся
 * без переписки, но с живым аккаунтом на сервере — и повторить
 * удаление ему больше нечем.
 *
 * Место, где этот порядок можно перепутать, должно быть одно, поэтому
 * экран вызывает [run], а не складывает два шага сам.
 *
 * # Почему локальное стирание не откатывается
 *
 * Обратного пути нет и быть не может: аккаунта на сервере уже нет,
 * и оставленная база открывала бы переписку, отправить в которую
 * ничего нельзя, а получить — тем более. Поэтому при успехе первого
 * шага второй выполняется всегда, даже если частично не удался;
 * о неудаче сообщается ([Outcome.wiped]), а не умалчивается.
 */
object DeleteAccount {

    /**
     * Чем закончилось удаление.
     *
     * @property report что сервер сообщил об удалённом.
     * @property wiped удалось ли убрать с устройства **всё**.
     *   `false` означает, что какой-то файл остался: человеку это
     *   показывается, потому что единственное оставшееся средство —
     *   удалить приложение, и знать об этом должен он, а не журнал.
     */
    data class Outcome(val report: FfiAccountDeletion, val wiped: Boolean)

    /**
     * Удаляет аккаунт на сервере, затем стирает его с устройства.
     *
     * Блокирующий вызов: ходит в сеть и в файловую систему. Вызывать
     * с фонового потока.
     *
     * @throws Exception если сервер не принял удаление. В этом случае
     *   на устройстве **ничего не тронуто** — попытку можно повторить,
     *   и это единственная причина, по которой исключение не гасится
     *   здесь: экран обязан отличить «не удалено» от «удалено».
     */
    fun run(context: Context): Outcome {
        val report = Core.messenger().deleteAccount(System.currentTimeMillis())

        return Outcome(report = report, wiped = AccountWipe.wipe(context))
    }
}
