package org.aegis.app.core

/**
 * 🔐 Можно ли писать в чат — по состоянию контакта, которое дало ядро.
 *
 * # Кто решает
 *
 * Решает ядро: отправка на ключ, который сервер назвал вместо
 * известного, отвергается там (`AegisError::IdentityChanged`) до
 * шифрования, и интерфейс обойти это не может. Этот объект лишь
 * заранее показывает то же решение, чтобы человек не набирал
 * сообщение, которое ядро всё равно не отправит, и видел, **почему**.
 *
 * # Что было
 *
 * Флаг смены ключа в `ChatActivity` был заглушкой — `false` навсегда,
 * а ядро ключ сервера при отправке не сверяло вовсе. Сервер,
 * назвавший свой ключ, получал следующее сообщение даже в сверенном
 * чате.
 */
object SendGuard {

    enum class Mode {
        /** Писать можно. */
        OPEN,

        /**
         * Под этим именем два действующих ключа. Отправка остановлена
         * до выбора: сверки вживую или явного принятия ключа.
         */
        CHOOSE_KEY,

        /**
         * Ключ этого чата заменён другим. Переписка остаётся для
         * чтения, новые сообщения — в чате действующего ключа.
         */
        REPLACED,
    }

    /**
     * @param keyChanged имя контакта известно под другим действующим ключом
     * @param replaced ключ этого контакта заменён
     *
     * Контакт, которого ещё нет (первый чат по имени), — [Mode.OPEN]:
     * ключ для него известен только от сервера, и ядро примет его
     * при первом использовании.
     */
    fun decide(keyChanged: Boolean, replaced: Boolean): Mode = when {
        replaced -> Mode.REPLACED
        keyChanged -> Mode.CHOOSE_KEY
        else -> Mode.OPEN
    }
}
