package org.aegis.app.core

/**
 * 🔐 Что переживает выбор места сохранения, а что нет.
 *
 * # Что здесь чинится
 *
 * Сохранение вложения не работало вовсе, и не сообщало об этом.
 *
 * Порядок был такой: скачать файл, расшифровать, положить байты
 * в поле экрана, открыть системный выбор места. Выбор места —
 * полноэкранная активность, то есть `ChatActivity.onStop`, а `onStop`
 * это поле обнулял: расшифрованное не должно переживать сворачивание.
 *
 * К возвращению из диалога байтов не было никогда. Обработчик
 * результата видел `null` и выходил молча — ни файла, ни ошибки.
 * Человек выбирал папку, нажимал «сохранить» и не получал ничего.
 *
 * > 📌 Оба решения по отдельности верны. `onStop` правильно стирает
 * > расшифрованное; диалог правильно спрашивает место до записи.
 * > Не работала связка, и ни один комментарий о ней не знал.
 *
 * # Почему порядок перевёрнут
 *
 * Теперь сначала спрашивается место, и только потом скачивается файл.
 * Через границу жизненного цикла переезжает **описание вложения**,
 * а не его содержимое.
 *
 * Разница в том, чем рискуешь. Прежде в памяти через весь диалог
 * лежал расшифрованный файл целиком. Теперь — описание: адрес
 * шифроблоба, размер, имя и ключ расшифровки.
 *
 * ⚠️ Ключ в описании есть, и это не мелочь. Но он и так лежит
 * в зашифрованной базе на устройстве, откуда описание и взято:
 * потеряв его, экран перечитает заново. Расшифрованный файл
 * не лежит больше нигде.
 *
 * # Правило
 *
 * [begin] ставит задачу, [take] забирает её и очищает,
 * [onScreenStopped] **не трогает ничего**. Последнее и есть всё
 * содержание этого класса: уход экрана в фон не отменяет сохранение,
 * потому что уход экрана в фон — и есть открытый диалог выбора места.
 *
 * ⚠️ Гибель процесса задачу теряет — и это правильно. Восстанавливать
 * её значило бы записать описание с ключом на диск, чего здесь
 * не делается нигде.
 */
class PendingSave<T> {

    private var pending: T? = null

    /** Ставит задачу сохранения. */
    fun begin(task: T) {
        pending = task
    }

    /**
     * Забирает задачу и очищает.
     *
     * 🔐 Второй вызов вернёт `null`: описание не остаётся в памяти
     * после того, как им воспользовались или отказались.
     */
    fun take(): T? {
        val task = pending
        pending = null

        return task
    }

    /** Есть ли незавершённое сохранение. */
    fun isPending(): Boolean = pending != null

    /**
     * 🔐 Уход экрана в фон. Намеренно не делает ничего.
     *
     * Метод существует, чтобы очистка в `onStop` имела здесь
     * единственный вид и не появилась заново сама собой: открытый
     * диалог выбора места — это и есть ушедший в фон экран.
     */
    @Suppress("EmptyFunctionBlock")
    fun onScreenStopped() {
    }
}
