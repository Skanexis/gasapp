package org.aegis.app.core

import android.app.KeyguardManager
import android.content.Context
import android.os.Build
import java.io.File

/**
 * Проверки состояния устройства, от которых зависит стойкость защиты
 * приложения.
 *
 * Раздел 19.2 («проверять `isDeviceSecure()`», «детект root — не
 * блокировать, но предупредить и снизить security score») и MASVS
 * RESILIENCE-1.
 *
 * # Почему это не блокировка
 *
 * 🔐 Ни одна из проверок не запрещает пользоваться приложением, и это
 * решение, а не недоделка. Отказ работать на устройстве с root:
 *
 *  * не останавливает того, кого должен: обход детекта root — известная
 *    задача с готовыми решениями (Magisk Hide и подобные), то есть
 *    блокировка отсеивает добросовестного владельца root и пропускает
 *    недобросовестного;
 *  * ломает работу исследователей безопасности — тех самых, на которых
 *    держится проверяемость (ADR-020) и будущая bug bounty;
 *  * выталкивает людей, у которых root стоит по единственной доступной
 *    причине: старое устройство без обновлений производителя.
 *
 * Поэтому результат идёт в центр безопасности как непройденная проверка
 * с объяснением, а не как отказ.
 */
object DeviceIntegrity {

    /**
     * Стоит ли на устройстве экран блокировки (PIN, графический ключ
     * или пароль).
     *
     * 🔐 Без него разваливается не одна функция, а вся схема хранения
     * ключей (раздел 7.3): ключ-обёртка в Android Keystore помечен
     * `setUserAuthenticationRequired`, а аппаратное хранилище считает
     * пользователя аутентифицированным по экрану блокировки. Нет экрана
     * — нет и этой привязки, и KEK доступен любому, кто взял телефон
     * в руки.
     *
     * Вдобавок биометрия на устройстве без экрана блокировки не
     * настраивается вовсе: система требует запасной способ.
     */
    fun hasScreenLock(context: Context): Boolean {
        val keyguard = context.getSystemService(Context.KEYGUARD_SERVICE) as? KeyguardManager
            ?: return false

        // isDeviceSecure, а не isKeyguardSecure: второй считает
        // защищённым и экран со свайпом без кода.
        return keyguard.isDeviceSecure
    }

    /**
     * Признаки того, что на устройстве получен root.
     *
     * ⚠️ Это эвристика, и она честно называется эвристикой. Проверяется
     * то, что оставляют после себя распространённые способы получения
     * root; целенаправленное сокрытие их убирает. Ложноотрицательный
     * ответ здесь вероятнее ложноположительного, и полагаться на «root
     * не найден» как на гарантию нельзя.
     *
     * Ровно поэтому результат идёт в предупреждение, а не в запрет:
     * защита, которую тривиально обходят, не должна принимать решений.
     */
    fun looksRooted(): Boolean =
        hasTestKeysBuild() || hasSuBinary() || hasRootPackageArtifacts()

    /**
     * Сборка подписана тестовыми ключами.
     *
     * Штатные прошивки подписываются `release-keys`. `test-keys`
     * означает сборку, собранную не производителем, — в том числе
     * кастомную прошивку с root из коробки.
     */
    private fun hasTestKeysBuild(): Boolean =
        Build.TAGS?.contains("test-keys") == true

    /**
     * Исполняемый файл `su` в типичных местах.
     *
     * Запускать его нельзя: попытка выполнить `su` на устройстве с root
     * показывает пользователю системный запрос на выдачу прав. Мессенджер,
     * спрашивающий root при запуске, выглядит ровно как то, чем он не
     * является. Проверяется только наличие файла.
     */
    private fun hasSuBinary(): Boolean = SU_PATHS.any { path ->
        runCatching { File(path).exists() }.getOrDefault(false)
    }

    /**
     * Следы менеджеров root в файловой системе.
     *
     * Проверяются файлы, а не установленные пакеты: запрос списка
     * пакетов на Android 11+ требует объявить `QUERY_ALL_PACKAGES`
     * в манифесте. 🔐 Это разрешение отдаёт приложению перечень всего,
     * что установлено на устройстве, — сведения о человеке, которые
     * мессенджеру не нужны и которые он обязуется не собирать
     * (раздел 15). Обнаружение root такой цены не стоит.
     */
    private fun hasRootPackageArtifacts(): Boolean = ROOT_ARTIFACTS.any { path ->
        runCatching { File(path).exists() }.getOrDefault(false)
    }

    private val SU_PATHS = listOf(
        "/sbin/su",
        "/system/bin/su",
        "/system/xbin/su",
        "/system/sbin/su",
        "/vendor/bin/su",
        "/su/bin/su",
        "/data/local/xbin/su",
        "/data/local/bin/su",
    )

    private val ROOT_ARTIFACTS = listOf(
        "/system/app/Superuser.apk",
        "/system/app/SuperSU",
        "/data/adb/magisk",
        "/sbin/magisk",
    )
}
