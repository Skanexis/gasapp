package org.aegis.app.core

/**
 * Ключи настроек приложения.
 *
 * # Зачем константы
 *
 * Ключ — это строка, по которой настройка находится в базе. Опечатка
 * в ней не ломает сборку: экран просто читает несуществующий ключ
 * и получает умолчание. 🔐 Для настроек безопасности это означает
 * тихое возвращение к состоянию по умолчанию — переключатель
 * показывает одно, а работает другое.
 *
 * # Про умолчания
 *
 * Умолчание хранится рядом с ключом, потому что оно часть смысла
 * настройки, а не деталь экрана. Разные экраны, читающие один ключ
 * с разными умолчаниями, дали бы разный ответ на один вопрос.
 */
object Settings {

    /**
     * Индикаторы набора и квитанции прочтения.
     *
     * 🔐 Выключено по умолчанию: обе функции сообщают собеседнику,
     * что человек сейчас у телефона, то есть выдают распорядок дня.
     * Функция, требующая отключения, защищает только тех, кто нашёл
     * настройку; требующая включения — всех остальных.
     */
    const val PRESENCE = "presence_sharing"

    /**
     * Показывать ли собеседнику время последнего входа.
     *
     * 🔐 Выключено по умолчанию по той же причине: «был в сети
     * 3 минуты назад» — это тоже распорядок дня, только менее точный.
     */
    const val LAST_SEEN = "last_seen_sharing"

    /**
     * Блокировать снимки экрана и содержимое в переключателе задач.
     *
     * 🔐 Включено по умолчанию. Здесь наоборот: защита не сообщает
     * ничего собеседнику и не мешает работе, а её отсутствие
     * показывает переписку любому, кто взял разблокированный телефон
     * или получил доступ к системным снимкам.
     *
     * Выключение осмысленно, когда человек снимает скриншоты сам —
     * например, чтобы переслать переписку юристу.
     */
    const val BLOCK_SCREENSHOTS = "block_screenshots"

    /**
     * Показывать текст сообщения в уведомлении.
     *
     * 🔐 Выключено по умолчанию: уведомление видно на заблокированном
     * экране, то есть любому, кто рядом с телефоном. Само уведомление
     * при этом не содержит текста и на стороне сервера (ADR-014) —
     * эта настройка про то, что подставит приложение уже на устройстве.
     */
    const val NOTIFICATION_PREVIEW = "notification_preview"

    /**
     * Звук и вибрация уведомлений.
     *
     * Включено по умолчанию: беззвучный мессенджер по умолчанию
     * означает пропущенные сообщения, а это не вопрос безопасности.
     */
    const val NOTIFICATION_SOUND = "notification_sound"

    /**
     * Через сколько секунд бездействия запирать приложение.
     *
     * 🔐 Пять минут по умолчанию. Без автозапирания разблокированное
     * приложение остаётся открытым до перезагрузки: телефон, оставленный
     * на столе, показывает переписку любому, кто его возьмёт.
     */
    const val AUTO_LOCK_SECONDS = "auto_lock_seconds"

    /** Умолчание автозапирания: пять минут. */
    const val AUTO_LOCK_DEFAULT = 300L
}
