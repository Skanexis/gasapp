package org.aegis.app.core

import android.content.Context
import java.io.File

/**
 * 🔐 Расшифрованные файлы хранилища не переживают процесс.
 *
 * # Что здесь чинится
 *
 * Чтобы показать файл из хранилища, его приходится расшифровать
 * на диск: системному просмотрщику нужен файл, а не массив байт.
 * Копия кладётся в `cacheDir/vault-open`.
 *
 * `VaultActivity.onStop` её удаляет — но только ту, что помнит
 * **список в памяти**. А `onStop` вызывается не всегда:
 *
 * * систему прижало по памяти и она убила процесс;
 * * человек снял приложение из недавних;
 * * «Остановить» в настройках, разряд батареи, падение.
 *
 * Во всех этих случаях расшифрованный файл остаётся лежать
 * открытым текстом — в хранилище, которое существует ровно затем,
 * чтобы такого не было. И не узнаёт об этом никто: приложение
 * при следующем запуске каталог не смотрело вовсе.
 *
 * # Почему подметание, а не аккуратное удаление
 *
 * Список в памяти после гибели процесса недоступен по определению.
 * Значит чистить надо **по каталогу**, а не по списку, и делать это
 * тогда, когда список заведомо пуст, — при открытии хранилища базы.
 *
 * ⚠️ Каталог принадлежит только этому механизму. Класть туда что-то
 * ещё нельзя: подметание не разбирает, чьё оно.
 *
 * # Чего это не даёт
 *
 * Гарантии невосстановимости. Удаление файла не затирает ячейки
 * флеш-памяти, и содержимое может быть поднято криминалистикой.
 * Обещать иное было бы неправдой; здесь закрывается другое —
 * файл перестаёт лежать на виду у любого, кто получит доступ
 * к каталогу приложения.
 */
object VaultTemp {

    /** Имя каталога временно расшифрованных файлов. */
    const val DIRECTORY = "vault-open"

    /** Имя, безопасное как имя файла в каталоге (см. [FileNames.safe]). */
    fun safeName(name: String): String = FileNames.safe(name)

    /**
     * Файл для расшифрованной копии: всегда внутри [directory].
     *
     * 🔐 Проверка по канонпути — вторая линия после [safeName]: записи,
     * сохранённые до исправления, несут имя как есть.
     */
    fun fileFor(context: Context, name: String): File {
        val root = directory(context).canonicalFile
        val target = File(root, safeName(name)).canonicalFile

        check(target.parentFile == root) { "имя файла выводит за каталог" }

        return target
    }

    /** Каталог временно расшифрованных файлов. */
    fun directory(context: Context): File =
        File(context.cacheDir, DIRECTORY).apply { mkdirs() }

    /**
     * Удаляет всё, что осталось от прошлых сеансов.
     *
     * Вызывается при открытии хранилища и при удалении аккаунта.
     * Возвращает число удалённых файлов — его показывают тесты,
     * а не пользователь: сообщать ему «мы убрали за собой то, что
     * не должны были оставлять» незачем.
     */
    fun sweep(context: Context): Int {
        val dir = File(context.cacheDir, DIRECTORY)

        if (!dir.isDirectory) {
            return 0
        }

        var removed = 0

        dir.listFiles()?.forEach { file ->
            if (runCatching { file.deleteRecursively() }.getOrDefault(false)) {
                removed += 1
            }
        }

        return removed
    }
}
