package org.aegis.app.push

/**
 * Способ доставки уведомлений о новых сообщениях.
 *
 * Реализация выбирается на этапе сборки flavor'ом, а не условием в коде:
 *
 * * `gms`  — Firebase Cloud Messaging (Google Play);
 * * `foss` — фоновый сокет без каких-либо сервисов Google (F-Droid).
 *
 * Разделение по flavor'ам, а не по `if`, — требование раздела 18.2 плана:
 * сборка для F-Droid обязана **физически не содержать** классов Google Play
 * Services, иначе она не проходит проверку на отсутствие проприетарных
 * зависимостей. Условие в общем коде оставило бы их в APK.
 *
 * ⚠️ Само содержимое push всегда пустое (content-free, ADR-014): уведомление
 * — это сигнал «сходи на сервер», а не текст сообщения. Ни один провайдер
 * ниже не получает доступа к содержимому переписки.
 */
interface PushProvider {

    /** Человекочитаемое имя механизма доставки — для экрана диагностики. */
    val displayName: String

    /** Доступен ли механизм на этом устройстве прямо сейчас. */
    fun isAvailable(): Boolean

    /**
     * Запускает доставку уведомлений.
     *
     * Вызывается после разблокировки клиента: до этого ключей для
     * расшифровки всё равно нет.
     */
    fun start()

    /** Останавливает доставку (выход из аккаунта, блокировка). */
    fun stop()
}
