package org.gasapp.app.net

import kotlin.math.abs

/**
 * Сверка часов устройства с часами сервера.
 *
 * Сервер принимает подписанный запрос, только если время его выпуска
 * отличается от серверного не больше чем на пять минут. Телефон с
 * неверными часами поэтому получает отказ на всё подряд, а выглядит это
 * как «сервер недоступен» — и человеку нечем понять, что чинить.
 *
 * Время сервера берётся из заголовка `Date` любого ответа. 🔐 Это
 * подсказка для экрана, а не источник времени: сами часы приложение не
 * трогает и подписывает запросы временем устройства. Сервер, солгавший
 * в `Date`, добьётся лишь лишней полосы «проверьте время».
 */
object ClockCheck {

    /** С какого расхождения полоса появляется: чуть раньше отказа сервера. */
    private const val LIMIT_MS = 4 * 60 * 1000L

    @Volatile
    private var skewMillis = 0L

    /** Запоминает расхождение по заголовку `Date`; `0` — заголовка нет. */
    fun observe(serverMillis: Long, nowMillis: Long = System.currentTimeMillis()) {
        if (serverMillis > 0) skewMillis = nowMillis - serverMillis
    }

    /** Часы устройства расходятся с серверными настолько, что запросы не пройдут. */
    val off: Boolean
        get() = abs(skewMillis) > LIMIT_MS
}
