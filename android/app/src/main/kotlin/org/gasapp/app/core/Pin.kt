package org.gasapp.app.core

/**
 * 🔐 Что такое PIN этого приложения — в одном месте.
 *
 * # Зачем отдельный объект ради одного числа
 *
 * Число было записано дважды, и записи разошлись.
 *
 * Экран входа — клавиатура на шесть точек: `append` обрывает ввод
 * на шестой цифре и сразу проверяет набранное. Другой длины он
 * выдать не может физически.
 *
 * Экран регистрации принимал **от шести до двенадцати**: поле стояло
 * с `maxLength="12"`, проверка была «не короче шести», а подсказка
 * под полем предлагала «не менее 6 цифр» — то есть приложение само
 * звало ввести то, чем потом не войти.
 *
 * # Чем это кончалось
 *
 * Ключ базы выводится из PIN целиком (Argon2id). PIN из семи цифр
 * давал ключ, который экран входа не воспроизведёт никогда: он
 * соберёт шесть цифр, получит другой ключ, и база не откроется.
 *
 * Отдельной проверки «верен ли PIN» в системе нет — она означала бы
 * хранить подсказку для перебора. Поэтому приложение не сказало бы
 * «PIN слишком длинный»; оно говорило бы «не удалось открыть»,
 * одинаково и навсегда. Переписка при этом цела и нечитаема,
 * и восстановить её можно только из резервной копии ключом
 * восстановления — если он есть.
 *
 * ⚠️ Дефект лежал на **обычном** пути: чтобы в него попасть, хватало
 * поверить подсказке под полем ввода.
 *
 * # Правило
 *
 * Регистрация принимает ровно то, что способен набрать экран входа,
 * — и длину, и алфавит. `LENGTH` здесь единственное; оба экрана
 * берут его отсюда, и разойтись им больше негде.
 */
object Pin {

    /** Длина PIN. Экран входа набирает ровно столько. */
    const val LENGTH = 6

    /**
     * Годится ли PIN для регистрации.
     *
     * 🔐 Цифры проверяются по коду, а не `isDigit()`: тот считает
     * цифрами и арабо-индийские, и деванагари. Клавиатура входа
     * выдаёт только ASCII, а вставить в поле можно что угодно.
     */
    fun isAcceptable(pin: ByteArray): Boolean =
        pin.size == LENGTH && pin.all { it in '0'.code.toByte()..'9'.code.toByte() }

    /**
     * 🔐 Слишком ли PIN прост, чтобы его выбирать (аудит 2026-10-02).
     *
     * Перебор начинают не с `000000` подряд, а со списка самых частых:
     * одна цифра, ряды, повторы пар и троек. По открытым утечкам такие
     * PIN — заметная доля всех шестизначных, и с ними задержки и
     * аппаратная половина ключа защищают минуты вместо суток.
     *
     * Проверяется только при **выборе** PIN: того, кто уже пользуется
     * простым, это не запирает.
     */
    fun isTooSimple(pin: ByteArray): Boolean {
        if (!isAcceptable(pin)) return false

        val digits = pin.map { it - '0'.code.toByte() }
        // Шаг по модулю 10: 135791 и 789012 «переходят» через 9 → 0 и
        // без модуля ускользали от правила (найдено тестами iOS).
        val steps = digits.zipWithNext { a, b -> (b - a + 10) % 10 }.toSet()

        // 111111, 123456, 654321, 135791 — шаг один и тот же.
        if (steps.size == 1) return true
        // 121212, 101010 — повтор пары; 123123 — повтор тройки.
        if ((2 until LENGTH).all { digits[it] == digits[it - 2] }) return true
        if ((3 until LENGTH).all { digits[it] == digits[it - 3] }) return true
        // 112233, 111222 — пары и тройки одинаковых.
        if ((0 until LENGTH step 2).all { digits[it] == digits[it + 1] } && digits.toSet().size <= 3) return true

        return String(pin, Charsets.US_ASCII) in COMMON
    }

    /**
     * Частые шестизначные PIN, которых не ловят правила выше: рисунки на
     * клавиатуре и «запоминающиеся» числа.
     */
    private val COMMON = setOf(
        "159753", "147258", "258369", "789456", "456123", "147852",
        "963852", "142536", "100200", "696969", "102030", "131313",
        "123654", "123321", "654456", "112358", "111222", "000111",
        "111000", "222111",
    )
}
