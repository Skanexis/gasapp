package org.gasapp.app.core

/**
 * 🔐 Можно ли писать в чат — по состоянию контакта, которое дало ядро.
 *
 * # Кто решает
 *
 * Решает ядро: отправка на ключ, который сервер назвал вместо
 * известного, отвергается там (`GasAppError::IdentityChanged`) до
 * шифрования, и интерфейс обойти это не может. Этот объект лишь
 * заранее показывает то же решение, чтобы человек не набирал
 * сообщение, которое ядро всё равно не отправит, и видел, **почему**.
 *
 * # Что было
 *
 * Флаг смены ключа в `ChatActivity` был заглушкой — `false` навсегда,
 * а ядро ключ сервера при отправке не сверяло вовсе. Сервер,
 * назвавший свой ключ, получал следующее сообщение даже в сверенном
 * чате.
 */
object SendGuard {

    enum class Mode {
        /** Писать можно. */
        OPEN,

        /**
         * Собеседник заблокирован: его сообщения отбрасываются, писать
         * ему нельзя. Снимается только кнопкой «Разблокировать».
         */
        BLOCKED,

        /**
         * Под этим именем два действующих ключа. Отправка остановлена
         * до сверки safety number вживую.
         */
        CHOOSE_KEY,

        /**
         * 🔐 Запрос на переписку от незнакомца. Читать можно; ответить —
         * после «Принять». До этого ему не уходят ни квитанции,
         * ни «печатает…».
         */
        REQUEST,

        /**
         * 🔐 Ключ назвал только сервер — сверки или ссылки собеседника
         * не было. Писать нельзя: сервер мог подставить свой ключ.
         */
        CONFIRM_KEY,

        /**
         * Ключ этого чата заменён другим. Переписка остаётся для
         * чтения, новые сообщения — в чате действующего ключа.
         */
        REPLACED,
    }

    /**
     * @param keyChanged имя контакта известно под другим действующим ключом
     * @param replaced ключ этого контакта заменён
     * @param keyConfirmed ключ подтверждён вне сервера — сверкой safety
     *   number или ссылкой/QR самого собеседника
     * @param request переписка — непринятый входящий запрос
     * @param blocked собеседник заблокирован
     *
     * Контакт, которого ещё нет, — неподтверждённый: ключ для него
     * знает только сервер.
     */
    fun decide(
        keyChanged: Boolean,
        replaced: Boolean,
        keyConfirmed: Boolean,
        request: Boolean = false,
        blocked: Boolean = false,
    ): Mode = when {
        // Блокировка — решение человека, и оно важнее всего остального:
        // сверять ключ или принимать запрос того, кого заблокировал, незачем.
        blocked -> Mode.BLOCKED
        replaced -> Mode.REPLACED
        keyChanged -> Mode.CHOOSE_KEY
        // Сначала согласие, потом сверка: сверять ключ с тем, с кем
        // человек не собирается разговаривать, незачем.
        request -> Mode.REQUEST
        !keyConfirmed -> Mode.CONFIRM_KEY
        else -> Mode.OPEN
    }
}
