package org.gasapp.app.core

import android.content.Context
import java.io.File

/**
 * 🔐 Стирание аккаунта с устройства (MASVS PRIVACY-3.2).
 *
 * # Почему это отдельно от удаления на сервере
 *
 * Сервер и устройство удаляются разными вызовами, и **порядок между
 * ними обязателен**: сначала сервер ([uniffi.gasapp.Messenger.deleteAccount]),
 * и только по его успеху — это. Наоборот — и при обрыве связи человек
 * остался бы без переписки, но с живым аккаунтом на сервере, а
 * повторить удаление стало бы нечем: запрос подписывается ключом,
 * который только что стёрли.
 *
 * Порядок держит [DeleteAccount], а не вызывающий экран: место, где
 * его можно перепутать, должно быть одно.
 *
 * # Что стирается
 *
 * Всё, что относится к аккаунту, а не к приложению: база, соль,
 * аппаратный секрет, ключ в Android Keystore и счётчик неверных
 * попыток PIN.
 *
 * ⚠️ Стирание — это удаление файлов, а не затирание секторов. На
 * флеш-памяти перезапись не попадает в те же ячейки, и обещать
 * невосстановимость было бы неправдой. Настоящая гарантия здесь
 * другая: содержимое базы зашифровано, ключ выводился из PIN
 * и невынимаемого ключа Keystore, и вместе с [HardwareKey.destroy]
 * расшифровать остатки нечем — даже подняв их с диска.
 */
object AccountWipe {

    /**
     * Стирает все следы аккаунта с устройства.
     *
     * Сначала закрывается хранилище: удалять открытый файл базы
     * SQLite можно, но её страницы остались бы в памяти процесса,
     * а журнал `-wal` пересоздался бы при закрытии — то есть часть
     * данных пережила бы удаление.
     *
     * Ошибки отдельных шагов не прерывают остальные: файл, который
     * не удалось убрать, не повод оставить рядом ещё пять.
     *
     * @return `true`, если после стирания на устройстве не осталось
     *   ни одного из перечисленных файлов. `false` означает, что
     *   что-то осталось, и это надо показать человеку, а не скрыть.
     */
    fun wipe(context: Context): Boolean {
        Core.close()

        var clean = true

        // Ключ Keystore — первым: без него всё остальное уже
        // нерасшифровываемо, даже если удаление файла не удастся.
        //
        // Сбой не прерывает стирание, но и не скрывается: оставшийся
        // ключ — это оставшийся след, и решать, что с этим делать,
        // человеку, а не молчащему коду.
        if (runCatching { HardwareKey.destroy() }.isFailure) {
            clean = false
        }
        if (runCatching { TeeKey.destroy(context) }.isFailure) {
            clean = false
        }

        // 🔐 Биометрический конверт и его ключ Keystore: в конверте
        // лежит ключ базы. Оставить его значило бы оставить вход
        // в удалённый аккаунт — при том что база уже стёрта, а вот
        // ключ от неё пережил бы удаление.
        runCatching { BiometricUnlock.disable(context) }

        // 🔐 Расшифрованные файлы хранилища лежат в кэше, а не
        // в filesDir, и списком ниже не покрывались: удаление
        // аккаунта оставляло их на диске открытым текстом.
        if (runCatching { VaultTemp.sweep(context) }.isFailure) {
            clean = false
        }

        runCatching { PinAttempts.forget(context) }

        // 🔐 Шифроблобы File Vault — в filesDir/vault, каталогом, и прежде
        // списком ниже не покрывались: экран обещал удалить «файлы»,
        // а блобы переживали удаление аккаунта. Они зашифрованы, но
        // ключ от них — это PIN, и удалённый аккаунт не должен оставлять
        // на диске ничего, что можно перебирать.
        val vault = File(context.filesDir, VAULT_DIRECTORY)
        if (vault.exists() && !runCatching { vault.deleteRecursively() }.getOrDefault(false)) {
            clean = false
        }

        for (name in FILES) {
            val file = File(context.filesDir, name)

            if (!file.exists()) {
                continue
            }

            if (!runCatching { file.delete() }.getOrDefault(false)) {
                clean = false
            }
        }

        // 🔐 Буфер обмена: за минуту до удаления человек мог скопировать
        // из переписки отпечаток или адрес. Таймер очистки живёт
        // в процессе и после выхода не сработает.
        runCatching { SecureClipboard.clear(context) }

        return clean &&
            FILES.none { File(context.filesDir, it).exists() } &&
            !File(context.filesDir, VAULT_DIRECTORY).exists()
    }

    /**
     * Файлы аккаунта.
     *
     * `-wal` и `-shm` — журнал опережающей записи SQLite и файл
     * разделяемой памяти. В журнале лежат страницы базы: удалить
     * `gasapp.db`, оставив `gasapp.db-wal`, значит оставить часть
     * переписки.
     */
    /** Каталог шифроблобов File Vault (см. `VaultActivity.vaultDir`). */
    const val VAULT_DIRECTORY = "vault"

    private val FILES = listOf(
        "gasapp.db",
        "gasapp.db-wal",
        "gasapp.db-shm",
        "gasapp.salt",
        "gasapp.hw",
        "gasapp.bio",
    )
}
